def validate_profiles(groups: dict = None) -> bool:
    """Verify all teams in groups have complete profiles."""
    if groups is None:
        from world_cup_engine import GROUPS
        groups = GROUPS

    all_teams = [t for teams in groups.values() for t in teams]
    missing = [t for t in all_teams if t not in TEAM_PROFILES]
    extra = [t for t in TEAM_PROFILES if t not in all_teams]

    if missing:
        print(f"ERROR: Teams in groups but missing profiles: {missing}")
        return False
    if extra:
        print(f"WARNING: Teams with profiles but not in any group: {extra}")

    # Verify all required keys exist
    required_keys = [
        "elo", "star_player_rating", "squad_depth", "tournament_pedigree",
        "recent_form", "offensive_rating", "defensive_rating",
        "manager_experience", "host_advantage", "key_players",
        "manager", "formation", "style", "wc_history", "strengths", "weaknesses",
        "gdp_pc", "population", "avg_temp",
    ]
    for team, profile in TEAM_PROFILES.items():
        for key in required_keys:
            if key not in profile:
                print(f"ERROR: {team} missing required key: {key}")
                return False

    print(f"OK: {len(TEAM_PROFILES)} team profiles validated successfully.")
    return True


